async (page) => {
  const check = (ok, message) => { if (!ok) throw new Error(message); };
  page.setDefaultTimeout(25000);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('http://127.0.0.1:4300/');
  await page.getByRole('button', { name: 'Khám phá Linear', exact: true }).click();
  const workflow = page.locator('app-experiment-workflow');
  await workflow.waitFor();
  await page.locator('#max-iterations').selectOption('100');
  await page.locator('#iteration-speed').selectOption('5');
  const record = workflow.getByRole('button', { name: 'Ghi nhận lần thử & so sánh', exact: true });
  await workflow.getByRole('button', { name: '2 · Cấu hình & câu hỏi', exact: true }).click();
  check(await workflow.locator('#trial-hypothesis').count() === 0, 'First run needs no hypothesis');
  await page.screenshot({ path: 'output/playwright/first-run-no-hypothesis.png' });
  await workflow.getByRole('button', { name: 'Chạy cấu hình ban đầu', exact: true }).click();
  await workflow.getByRole('button', { name: '4 · Đánh giá', exact: true }).click();
  await record.waitFor(); await page.waitForFunction(() => !document.querySelector('app-experiment-workflow .stage-body button.primary')?.disabled);
  check(await page.getByText('Test cuối ·', { exact: false }).count() === 0, 'Test must remain hidden before explicit final evaluation');
  await record.click();
  check(await workflow.locator('.trial-log tbody tr').count() === 1, 'First trial recorded');
  check((await workflow.locator('.trial-log tbody tr').innerText()).includes('Chạy cấu hình ban đầu'), 'Baseline purpose captured with trial');
  await workflow.getByRole('button', { name: 'Chuẩn bị lần thử tiếp (giữ dữ liệu)', exact: true }).click();
  await page.locator('#learning-rate').selectOption('0.03');
  await page.setViewportSize({ width: 390, height: 844 });
  await workflow.scrollIntoViewIfNeeded();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Question selector fits mobile');
  await page.screenshot({ path: 'output/playwright/optional-question-mobile.png' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await workflow.locator('#trial-question').selectOption({ label: 'Tăng số vòng tối đa có giúp giảm sai số validation không?' });
  await workflow.getByText('Tự viết câu hỏi hoặc dự đoán (tùy chọn)', { exact: true }).click();
  await page.getByLabel('Bạn dự đoán điều gì trước lần chạy này?', { exact: true }).fill('Tăng alpha trên cùng dữ liệu để so sánh.');
  await workflow.getByRole('button', { name: 'Chạy cấu hình này', exact: true }).click();
  await workflow.getByRole('button', { name: '4 · Đánh giá', exact: true }).click();
  await record.waitFor(); await page.waitForFunction(() => !document.querySelector('app-experiment-workflow .stage-body button.primary')?.disabled);
  await record.click();
  check(await workflow.locator('.trial-log tbody tr').count() === 2, 'Two independent trial snapshots');
  await workflow.getByText('so với mốc #1', { exact: false }).waitFor();
  check((await workflow.innerText()).includes('so với mốc #1'), 'Comparison against baseline visible');
  await workflow.getByRole('button', { name: '4 · Đánh giá', exact: true }).click();
  check(await workflow.getByRole('table', { name: 'Kết quả hiện tại so với mốc' }).count() === 1, 'Side-by-side baseline metrics');
  await workflow.getByRole('table', { name: 'Kết quả hiện tại so với mốc' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'output/playwright/baseline-comparison.png' });
  await workflow.getByRole('button', { name: 'Chọn cấu hình hiện tại & đánh giá test', exact: true }).click();
  await workflow.getByText('Test cuối ·', { exact: false }).waitFor();
  check((await workflow.innerText()).includes('không còn là đánh giá độc lập'), 'Repeated test exposure warning');
  await page.screenshot({ path: 'output/playwright/experiment-workflow-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Học từng bước và ghi chú', exact: false }).click();
  const progress = page.locator('#lab [role=progressbar]');
  const next = page.locator('.run-iteration');
  await next.click();
  await page.waitForFunction(() => document.querySelector('#learning .lesson-illustration')?.getAttribute('data-view-phase') === '0');
  await page.waitForTimeout(1200);
  check(await progress.getAttribute('aria-valuenow') === '0', 'Manual A waits without committing');
  const model = page.locator('#learning app-viewport3d');
  const panel = page.locator('app-learning-walkthrough');
  const modelBox = await model.boundingBox(), panelBox = await panel.boundingBox();
  check(modelBox.x < panelBox.x, '3D stays left, explanation stays right');
  for (let phase = 1; phase < 6; phase++) {
    await next.click();
    await page.waitForFunction(phase => document.querySelector('#learning .lesson-illustration')?.getAttribute('data-view-phase') === String(phase), phase);
    check(await progress.getAttribute('aria-valuenow') === (phase < 5 ? '0' : '1'), 'Only F commits once');
  }
  await page.waitForTimeout(1200);
  check(await progress.getAttribute('aria-valuenow') === '1', 'F waits for another explicit click');
  await page.locator('.stage-toggle').nth(1).click();
  await page.waitForFunction(() => document.querySelector('#learning .lesson-illustration')?.getAttribute('data-view-phase') === '1');
  check(await progress.getAttribute('aria-valuenow') === '1', 'Review does not train');
  check(await model.locator('canvas').count() === 1, 'Real 3D canvas mounted');
  await page.screenshot({ path: 'output/playwright/manual-learning-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await next.scrollIntoViewIfNeeded();
  check(await next.isVisible() && await next.isEnabled(), 'Manual next control remains usable on mobile');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Mobile has no page overflow');
  await page.screenshot({ path: 'output/playwright/manual-learning-mobile.png' });
  return { suite: 'experiment-workflow', passed: ['validation tuning', 'independent trial records', 'worker timing display', 'explicit final test', 'manual A-F', 'left-right layout', 'review without training', 'mobile layout'] };
}
